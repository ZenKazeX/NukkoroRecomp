MixerHistory Mixer::history() const noexcept {
    const EffectStage::History effect = effect_.history();
    MixerHistory saved;
    saved.compressor_release = compressor_counter_;
    saved.aux_b_return = effect.output.matrix;
    saved.source = history_;
    saved.main_surround = effect.output.surround;
    saved.alternate_matrix = effect.output.alternate_matrix;
    saved.alternate_return = effect.output.alternate_return;
    saved.effect = effect.effect;
    saved.pending = effect.pending;
    saved.spatial_right = effect.spatial_right;
    saved.next = static_cast<std::uint8_t>(effect.next);
    saved.awaiting = effect.awaiting;
    return saved;
}

bool Mixer::restore_history(const MixerHistory& saved) noexcept {
    if (saved.compressor_release > 10u) return false;
    // The schedule comes from each block's command list, so the stage's own control values are not history here.
    EffectStage::History effect;
    effect.effect = saved.effect;
    effect.output = {saved.main_surround, saved.aux_b_return, saved.alternate_matrix, saved.alternate_return};
    effect.pending = saved.pending;
    effect.spatial_right = saved.spatial_right;
    effect.next = saved.next;
    effect.awaiting = saved.awaiting;
    if (!effect_.restore(effect)) return false;
    compressor_counter_ = saved.compressor_release;
    history_ = saved.source;
    return true;
}

void Mixer::reset() noexcept {
    for (Buffer& b : bus_) b.fill(0);
    effect_ = EffectStage{};
    for (auto& h : history_) h.fill(0);
    compressor_counter_ = 0;
}

void Mixer::compress(const FrameSettings& settings, MixStats& stats) noexcept {
    // Command 0x12 (IRAM 0x0082..0x0113), run after every return and before the output.
    if (!settings.compressor) return;
    // Detection (0x008D..0x009A, SET40): every one of the 320 main L then main R s32 samples, ABS, CMP against the
    // threshold (loaded into AC1.L alone: 0x8000 = +32768); IFC (carry: |x| >= threshold) sets the flag. ">=" is the
    // interpreter's carry rule (SINGLE-SOURCE, 05 section 13).
    const std::int64_t threshold = settings.compressor_threshold;
    bool triggered = false;
    for (std::uint32_t c = 0; c < 2u && !triggered; ++c) {
        const Buffer& b = bus_[c == 0u ? kMainL : kMainR];
        for (std::uint32_t i = 0; i < kFrameSamples; ++i) {
            const std::int64_t v = b[i];
            if ((v < 0 ? -v : v) >= threshold) {
                triggered = true;
                break;
            }
        }
    }
    // Row selection (0x009B..0x00D6): triggered -> row = the release counter BEFORE the frame, counter = release
    // frames; not triggered and counter > 0 -> counter -= 1, row = 11 + counter; not triggered and counter == 0 ->
    // nothing is applied.
    std::int32_t row = -1;
    if (triggered) {
        row = compressor_counter_;
        compressor_counter_ = settings.compressor_release_frames;
    } else if (compressor_counter_ != 0u) {
        --compressor_counter_;
        row = 11 + compressor_counter_;
    }
    stats.compressor_triggered = triggered;
    stats.compressor_row = row;
    if (row < 0 || row >= static_cast<std::int32_t>(kCompressorRows)) return;  // the boundary admits release <= 10
    // Application (0x00E5..0x0113, M2 SET15 SET40): x = floor(x * g / 32768) per sample, g unsigned (exact while
    // |x| < 2^23, the 40-bit headroom of the hi * g * 2 << 16 product; main buses stay far below it).
    const std::uint16_t* gain = kCompressorGain.data() + static_cast<std::size_t>(row) * kFrameSamples;
    for (std::uint32_t c = 0; c < 2u; ++c) {
        Buffer& b = bus_[c == 0u ? kMainL : kMainR];
        for (std::uint32_t i = 0; i < kFrameSamples; ++i) {
            b[i] = static_cast<std::int32_t>((static_cast<std::int64_t>(b[i]) * gain[i]) >> 15);
        }
    }
}

void Mixer::render_voice(const VoiceFrame& voice, MixStats& stats) noexcept {
    const std::uint32_t mc = voice.mixer_control;
    if (voice.envelope_delta != 0u) ++stats.enveloped_voices;
    if (mc & kRampBits) ++stats.ramped_voices;
    if ((voice.volume[kMainL].value | voice.volume[kMainR].value) != 0u && voice.envelope != 0u) ++stats.voices_mixed;

    // ---- sample-rate conversion (section 7.2), for every running voice whatever its gains (IRAM 0x0310..0x031D
    // runs SRC before the envelope and the mix) ----
    std::array<std::int16_t, 4>& history = history_[voice.slot % kMaxVoices];
    if (voice.restart) history = voice.start_history;
    // The window: w(j) = the 4 samples read before this frame for j < 4, then source[j - 4] (silence at or past count).
    const auto w = [&](std::uint64_t j) -> std::int32_t {
        return j < 4u ? history[static_cast<std::size_t>(j)] : voice.source.at(j - 4u);
    };
    // The same window laid out flat - history, the source, then silence - so the per-sample SRC reads are plain loads
    // instead of two range tests each (2026-11-04: render_voice 0.053 ms/frame on the game thread). Covers every w(j)
    // the frame reads: j <= n + 3, n = (frac + 160 * ratio) >> 16; a voice reaching further (ratio above what the
    // window holds) keeps w.
    constexpr std::size_t kFlat = 4u + 1024u + 4u;
    const std::uint64_t reach = ((voice.frac + static_cast<std::uint64_t>(kFrameSamples) * voice.ratio) >> 16) + 4u;
    std::array<std::int16_t, kFlat> flat;
    const bool use_flat = reach <= kFlat;
    if (use_flat) {
        std::copy(history.begin(), history.end(), flat.begin());
        const std::size_t from_source =
            static_cast<std::size_t>(std::min<std::uint64_t>(voice.source.count, reach > 4u ? reach - 4u : 0u));
        if (from_source != 0u) std::copy_n(voice.source.samples, from_source, flat.begin() + 4);
        std::fill(flat.begin() + 4 + static_cast<std::ptrdiff_t>(from_source),
                  flat.begin() + static_cast<std::ptrdiff_t>(reach), std::int16_t{0});
    }
    std::array<std::int32_t, kFrameSamples> y{};
    if (voice.src == SrcMode::Linear && use_flat) {
        // As the loop below, reading the flat window.
        for (std::uint32_t i = 0; i < kFrameSamples; ++i) {
            const std::uint64_t t = voice.frac + static_cast<std::uint64_t>(i + 1u) * voice.ratio;
            const std::size_t k = static_cast<std::size_t>(t >> 16);
            const std::int64_t f = static_cast<std::int64_t>(t & 0xFFFFu);
            const std::int32_t s0 = flat[k + 2u];
            const std::int32_t d = sat16(static_cast<std::int64_t>(flat[k + 3u]) - s0);
            y[i] = sat16(s0 + product_round16(static_cast<std::int64_t>(d) * f));
        }
    } else if (voice.src == SrcMode::Linear) {
        // src_type 1 (IRAM 0x0753..0x0813): per output the phase is advanced FIRST (0x07D9 ADDAX), the two NEWEST taps
        // of the window are taken (0x07DA..0x07DD), their difference is stored through the saturating accumulator read
        // (0x07DE) and the output is s0 + rounded(d * f / 65536) (MULX signed x unsigned 0x0803, ADDPAXZ 0x0804). The
        // per-ms phase carry makes the frame-global phase t_i = frac + (i + 1) * ratio exact. Taps and phase:
        // CONFIRMED-BINARY; the stand-in sampled at i*ratio + frac instead, (2 - ratio) source samples ahead.
        for (std::uint32_t i = 0; i < kFrameSamples; ++i) {
            const std::uint64_t t = voice.frac + static_cast<std::uint64_t>(i + 1u) * voice.ratio;
            const std::uint64_t k = t >> 16;
            const std::int64_t f = static_cast<std::int64_t>(t & 0xFFFFu);
            const std::int32_t s0 = w(k + 2u);
            const std::int32_t d = sat16(static_cast<std::int64_t>(w(k + 3u)) - s0);
            y[i] = sat16(s0 + product_round16(static_cast<std::int64_t>(d) * f));
        }
    } else {
        // Polyphase needs the DSP ROM's coefficients (not in the game binary) and "none" reads one sample per output;
        // neither is used by this game (AU_REPORT.md section 2: every voice is linear). They keep the former stand-in
        // arithmetic (floor two-tap at i*ratio + frac; none = nearest).
        for (std::uint32_t i = 0; i < kFrameSamples; ++i) {
            const std::uint64_t pos = static_cast<std::uint64_t>(i) * voice.ratio + voice.frac;
            const std::uint32_t frac = voice.src == SrcMode::None ? 0u : static_cast<std::uint32_t>(pos & 0xFFFFu);
            const std::int64_t a = voice.source.at(pos >> 16);
            const std::int64_t b = frac != 0u ? voice.source.at((pos >> 16) + 1u) : a;
            y[i] = static_cast<std::int32_t>((a * (0x10000 - frac) + b * frac) >> 16);
        }
    }
    {
        // The window after the frame: the 4 newest samples read (the frame consumed n new samples).
        const std::uint64_t n = (voice.frac + static_cast<std::uint64_t>(kFrameSamples) * voice.ratio) >> 16;
        std::array<std::int16_t, 4> next{};
        for (std::uint32_t j = 0; j < 4u; ++j)
            next[j] = use_flat ? flat[static_cast<std::size_t>(n + j)] : static_cast<std::int16_t>(w(n + j));
        history = next;
    }

    // ---- volume envelope (section 7.4): signed Q15 stepped by delta every sample, x = sat16(floor(v * y / 32768))
    // (MUL is signed; M2 doubles, the >>16 halves) ----
    if (voice.envelope == 0u && voice.envelope_delta == 0u) return;  // every contribution below is zero
    std::array<std::int32_t, kFrameSamples> scaled{};
#if defined(__AVX2__)
    static_assert(kFrameSamples % 8 == 0, "SIMD blocks must contain whole vectors");
    // Eight independent signed Q15 gains. Low 16 bits retain the envelope's
    // wrapping ramp; each sample product fits int32, then saturates to int16.
    const __m256i lanes = _mm256_setr_epi32(0, 1, 2, 3, 4, 5, 6, 7);
    const __m256i low = _mm256_set1_epi32(-32768);
    const __m256i high = _mm256_set1_epi32(32767);
    __m256i envelope = _mm256_add_epi32(_mm256_set1_epi32(voice.envelope),
        _mm256_mullo_epi32(lanes, _mm256_set1_epi32(voice.envelope_delta)));
    const __m256i envelope_step = _mm256_set1_epi32(8 * voice.envelope_delta);
    for (std::uint32_t i = 0; i < kFrameSamples; i += 8) {
        const __m256i signed_gain = _mm256_srai_epi32(_mm256_slli_epi32(envelope, 16), 16);
        const __m256i samples = _mm256_loadu_si256(reinterpret_cast<const __m256i*>(y.data() + i));
        const __m256i product = _mm256_srai_epi32(_mm256_mullo_epi32(samples, signed_gain), 15);
        _mm256_storeu_si256(reinterpret_cast<__m256i*>(scaled.data() + i),
            _mm256_min_epi32(high, _mm256_max_epi32(low, product)));
        envelope = _mm256_add_epi32(envelope, envelope_step);
    }
#else
    for (std::uint32_t i = 0; i < kFrameSamples; ++i) {
        const std::int16_t v = static_cast<std::int16_t>(
            static_cast<std::uint16_t>(voice.envelope + i * static_cast<std::uint32_t>(voice.envelope_delta)));
        scaled[i] = sat16((static_cast<std::int32_t>(v) * y[i]) >> 15);
    }

#endif

    // ---- host category gain (not in the microcode): Q15 multiply of the enveloped voice, before every bus send, so
    // its reverb send follows it. Unity does nothing - the default output is the DSP's, bit for bit. ----
    if (voice.gain < kUnityVoiceGain) {
        const std::int32_t g = static_cast<std::int32_t>(voice.gain);
        for (std::uint32_t i = 0; i < kFrameSamples; ++i) scaled[i] = (scaled[i] * g) >> 15;
    }

    // ---- mixing into the enabled buses (section 7.6): dst += floor(x * v / 32768); a ramping bus steps its volume
    // by delta every sample (v_i = vol + i*delta, mod 2^16) ----
    for (const Route& route : kRoutes) {
        if ((mc & route.enable) == 0u) continue;
        const BusVolume vol = voice.volume[route.bus];
        const bool ramp = (mc & route.ramp) != 0u;
        Buffer& dst = bus_[route.bus];
#if defined(__AVX2__)
        // Unsigned Q15 bus gains still produce signed int32 products. Retain
        // saturating addition even for extreme restored bus history: overflow
        // occurs only when same-sign inputs produce the opposite-sign sum.
        const __m256i delta = _mm256_set1_epi32(ramp ? vol.delta : 0);
        __m256i gain = _mm256_add_epi32(_mm256_set1_epi32(vol.value), _mm256_mullo_epi32(lanes, delta));
        const __m256i step = _mm256_slli_epi32(delta, 3);
        const __m256i mask = _mm256_set1_epi32(0xFFFF);
        const __m256i maximum = _mm256_set1_epi32(0x7FFFFFFF);
        for (std::uint32_t i = 0; i < kFrameSamples; i += 8) {
            const __m256i samples = _mm256_loadu_si256(reinterpret_cast<const __m256i*>(scaled.data() + i));
            const __m256i contribution = _mm256_srai_epi32(
                _mm256_mullo_epi32(samples, _mm256_and_si256(gain, mask)), 15);
            const __m256i previous = _mm256_loadu_si256(reinterpret_cast<const __m256i*>(dst.data() + i));
            const __m256i sum = _mm256_add_epi32(previous, contribution);
            const __m256i overflow = _mm256_srai_epi32(_mm256_andnot_si256(
                _mm256_xor_si256(previous, contribution), _mm256_xor_si256(previous, sum)), 31);
            const __m256i limit = _mm256_xor_si256(maximum, _mm256_srai_epi32(previous, 31));
            _mm256_storeu_si256(reinterpret_cast<__m256i*>(dst.data() + i),
                _mm256_blendv_epi8(sum, limit, overflow));
            gain = _mm256_add_epi32(gain, step);
        }
#else
        for (std::uint32_t i = 0; i < kFrameSamples; ++i) {
            const std::int32_t v = ramp ? static_cast<std::uint16_t>(vol.value + i * static_cast<std::uint32_t>(vol.delta))
                                        : vol.value;
            dst[i] = sat32(static_cast<std::int64_t>(dst[i]) + ((scaled[i] * v) >> 15));
        }
#endif
    }
}

void Mixer::mix(const FrameSettings& settings, const VoiceFrame* voices, std::uint32_t count, StereoFrame& out,
                MixStats& stats) noexcept {
    stats = MixStats{};
    for (unsigned bus = kAuxAL; bus < kBusCount; ++bus) bus_[bus].fill(0);
    const auto mode = output_mode(settings.mode);
    // The microcode's order: the output mode's fold, the voices, the aux send/return (commands 0x04 / 0x13 / 0x10),
    // then the compressor and the output.
    effect_.begin(mode, bus_[kMainL], bus_[kMainR], bus_[kMainS]);
    for (std::uint32_t v = 0; v < count; ++v) render_voice(voices[v], stats);
    const EffectStage::Channels room{bus_[kAuxAL], bus_[kAuxAR], bus_[kAuxAS]};
    const EffectStage::Channels spatial{bus_[kAuxBL], bus_[kAuxBR], bus_[kAuxBS]};
    effect_.finish({mode, settings.aux_a}, bus_[kMainL], bus_[kMainR], bus_[kMainS], room, spatial);
    compress(settings, stats);
    // Output (command 0x0E): each main bus sample saturated to s16.
    for (std::uint32_t i = 0; i < kFrameSamples; ++i) {
        std::int16_t* const channel[2] = {&out.left[i], &out.right[i]};
        const std::int32_t bus[2] = {bus_[kMainL][i], bus_[kMainR][i]};
        for (std::uint32_t c = 0; c < 2u; ++c) {
            std::int32_t value = bus[c];
            if (value > 32767) value = 32767;
            if (value < -32768) value = -32768;
            if (value > stats.peak) stats.peak = value;
            if (-value > stats.peak) stats.peak = -value;
            *channel[c] = static_cast<std::int16_t>(value);
        }
    }
}

