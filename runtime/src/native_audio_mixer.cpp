inline std::int32_t sat32(std::int64_t v) noexcept {
    return v > 0x7FFFFFFF ? 0x7FFFFFFF : (v < -0x7FFFFFFFLL - 1 ? -0x7FFFFFFF - 1 : static_cast<std::int32_t>(v));
}

inline std::int32_t sat16(std::int64_t v) noexcept {
    return v > 32767 ? 32767 : (v < -32768 ? -32768 : static_cast<std::int32_t>(v));
}

// ADDPAXZ (IRAM 0x0804..0x080F): the 32-bit product d*f is added to s0 held in the accumulator's middle word and the
// low word is cleared, i.e. the product is reduced to 16 fractional bits. Rounding: half to even (+0x8000 when bit 16
// is set, else +0x7FFF, then drop the low 16 bits) - SINGLE-SOURCE (Dolphin interpreter, GetLongProductRounded); no
// independent second source was found (the DSP users' manual states no rounding step; AU_REPORT.md 5b, D-AU2).
inline std::int64_t product_round16(std::int64_t p) noexcept {
    return (p + ((p & 0x10000) ? 0x8000 : 0x7FFF)) >> 16;
}

