#!/usr/bin/env python3
"""Writes runtime/src/gekko/options_display_tile.inc: the Display tile's two 82 x 82 images (normal and selected,
made by make_display_icon.py and approved by the user on 2026-10-28) as RGBA8 bytes, for
gekko/native_options_display.h's place_tile_art, which writes them into cells 46 and 52 of Options2.

    python tools/options_menu_sim/emit_display_tile_inc.py
"""
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
ART = os.path.normpath(os.path.join(ROOT, '..', 'exports', 'options-menu-textures', 'new-display-tile'))
OUT = os.path.join(ROOT, 'runtime', 'src', 'gekko', 'options_display_tile.inc')


def rows(name):
    im = Image.open(os.path.join(ART, name)).convert('RGBA')
    if im.size != (82, 82):
        sys.exit('%s is %dx%d, not 82x82' % (name, im.size[0], im.size[1]))
    data = im.tobytes()
    out = []
    for i in range(0, len(data), 24):
        out.append('    ' + ', '.join('0x%02X' % b for b in data[i:i + 24]) + ',')
    return out


def main():
    lines = ['// Generated by tools/options_menu_sim/emit_display_tile_inc.py from',
             '// exports/options-menu-textures/new-display-tile/display_tv{,_selected}.png - do not edit.',
             '// The Display tile, 82 x 82 RGBA8, rows top to bottom.',
             'constexpr unsigned kTileSide = 82;',
             'const unsigned char kTileNormal[kTileSide * kTileSide * 4] = {']
    lines += rows('display_tv.png')
    lines += ['};', 'const unsigned char kTileSelected[kTileSide * kTileSide * 4] = {']
    lines += rows('display_tv_selected.png')
    lines += ['};', '']
    with open(OUT, 'wb') as f:
        f.write('\n'.join(lines).encode('ascii'))
    print('wrote', OUT)


if __name__ == '__main__':
    main()
