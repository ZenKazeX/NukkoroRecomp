#!/usr/bin/env python3
"""Writes runtime/src/gekko/options_menu_tiles.inc: the six category tiles of the PC Options menu (normal and
selected, 82 x 82 RGBA8, made by make_tile_icons.py; approved by the user on 2026-11-05), in grid order
Display, Graphics, Audio, Controls, Save Data, System (item = row * 2 + column). gekko/native_options_display.h's
place_tile_art writes them into Options2's cells 41..46 (normal) and 47..52 (selected).

    python tools/options_menu_sim/emit_tile_art_inc.py
"""
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
ART = os.path.normpath(os.path.join(ROOT, '..', 'exports', 'options-menu-textures', 'new-category-tiles'))
OUT = os.path.join(ROOT, 'runtime', 'src', 'gekko', 'options_menu_tiles.inc')
ORDER = ('display', 'graphics', 'audio', 'controls', 'savedata', 'system')


def rows(name):
    im = Image.open(os.path.join(ART, name)).convert('RGBA')
    if im.size != (82, 82):
        sys.exit('%s is %dx%d, not 82x82' % (name, im.size[0], im.size[1]))
    data = im.tobytes()
    return ['    ' + ', '.join('0x%02X' % b for b in data[i:i + 24]) + ',' for i in range(0, len(data), 24)]


def main():
    lines = ['// Generated by tools/options_menu_sim/emit_tile_art_inc.py from',
             '// exports/options-menu-textures/new-category-tiles/*.png - do not edit.',
             '// The six category tiles, 82 x 82 RGBA8, rows top to bottom: [item][0 normal, 1 selected].',
             'constexpr unsigned kTileSide = 82;',
             'const unsigned char kTileArt[6][2][kTileSide * kTileSide * 4] = {']
    for name in ORDER:
        lines.append('  {{')
        lines += rows(name + '.png')
        lines.append('  }, {')
        lines += rows(name + '_selected.png')
        lines.append('  }},')
    lines += ['};', '']
    with open(OUT, 'wb') as f:
        f.write('\n'.join(lines).encode('ascii'))
    print('wrote', OUT)


if __name__ == '__main__':
    main()
