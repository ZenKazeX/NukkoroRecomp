#!/usr/bin/env python3
"""Writes runtime/src/gekko/pc_save_texts.inc: the PC save wording of FR, GE, IT, JP, SP (pc_save_<lang>.json, each
checked with check_save.py first). English stays in native_save_text.cpp (pc_english_messages).

    python tools/options_menu_sim/save_text/emit_pc_save_inc.py
"""
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, '..', '..', '..', 'runtime', 'src', 'gekko', 'pc_save_texts.inc'))
LANGS = ('FR', 'GE', 'IT', 'JP', 'SP')


def c_string(text):
    out, prev_hex = ['"'], False
    for b in text.encode('utf-8'):
        ch = chr(b)
        if b == 0x0A:
            out.append('\\n'); prev_hex = False
        elif b in (0x22, 0x5C):
            out.append('\\' + ch); prev_hex = False
        elif 0x20 <= b < 0x7F:
            if prev_hex and ch in '0123456789abcdefABCDEF':
                out.append('" "')
            out.append(ch); prev_hex = False
        else:
            out.append('\\x%02X' % b); prev_hex = True
    out.append('"')
    return ''.join(out)


def main():
    lines = ['// Generated by tools/options_menu_sim/save_text/emit_pc_save_inc.py - do not edit.',
             '// The save messages in PC words (docs/SAVE_SCREEN_OPTIONS.md option A), per Save_<suffix>.fnt.',
             'struct PcSaveText {',
             '    const char* suffix;',
             '    u32 id;',
             '    const char* text;  // UTF-8',
             '};',
             'const PcSaveText kPcSaveTexts[] = {']
    for lang in LANGS:
        check = subprocess.run([sys.executable, os.path.join(HERE, 'check_save.py'), lang], capture_output=True,
                               text=True, encoding='utf-8')
        if check.returncode != 0:
            sys.exit('pc_save_%s.json fails check_save.py:\n%s' % (lang.lower(), check.stdout))
        data = json.load(open(os.path.join(HERE, 'pc_save_%s.json' % lang.lower()), encoding='utf-8'))
        for key in sorted(data, key=int):
            lines.append('    {"%s", %su, %s},' % (lang, key, c_string(data[key])))
    lines += ['};', '']
    with open(OUT, 'wb') as f:
        f.write('\n'.join(lines).encode('ascii'))
    print('wrote', OUT)


if __name__ == '__main__':
    main()
