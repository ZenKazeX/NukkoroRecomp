#!/usr/bin/env python3
"""Writes runtime/src/gekko/options_menu_texts.inc: the PC Options menu's texts in the six front-end languages, from
tools/options_menu_sim/i18n/strings_<lang>.json (English authored, the others translated and checked with
check_strings.py against each language's glyph sheets). A key a language lacks falls back to English.

    python tools/options_menu_sim/emit_menu_texts_inc.py

The table's language order is gekko::options_display::Language's: EN, FR, GE, IT, JP, SP.
"""
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
I18N = os.path.join(HERE, 'i18n')
OUT = os.path.join(ROOT, 'runtime', 'src', 'gekko', 'options_menu_texts.inc')
LANGS = ('en', 'fr', 'ge', 'it', 'jp', 'sp', 'hu')  # hu: Hungarian on the English slot (index 6)


def c_string(text):
    """A C string literal of `text` in UTF-8, every non-ASCII byte as a \\x escape (split so a following hex digit is
    never swallowed), newlines as \\n."""
    out = ['"']
    raw = text.encode('utf-8')
    prev_hex = False
    for b in raw:
        ch = chr(b)
        if b == 0x0A:
            out.append('\\n')
            prev_hex = False
        elif b == 0x22:
            out.append('\\"')
            prev_hex = False
        elif b == 0x5C:
            out.append('\\\\')
            prev_hex = False
        elif 0x20 <= b < 0x7F:
            if prev_hex and ch in '0123456789abcdefABCDEF':
                out.append('" "')
            out.append(ch)
            prev_hex = False
        else:
            out.append('\\x%02X' % b)
            prev_hex = True
    out.append('"')
    return ''.join(out)


def main():
    en = json.load(open(os.path.join(I18N, 'strings_en.json'), encoding='utf-8'))
    keys = [k for k in en if not k.startswith('_')]
    tables = {}
    for lang in LANGS:
        path = os.path.join(I18N, 'strings_%s.json' % lang)
        if lang != 'en' and os.path.exists(path):
            check = subprocess.run([sys.executable, os.path.join(I18N, 'check_strings.py'), lang.upper()],
                                   capture_output=True, text=True)
            if check.returncode != 0:
                sys.exit('strings_%s.json fails check_strings.py:\n%s' % (lang, check.stdout))
        tables[lang] = json.load(open(path, encoding='utf-8')) if os.path.exists(path) else {}
    lines = ['// Generated by tools/options_menu_sim/emit_menu_texts_inc.py from tools/options_menu_sim/i18n - do not edit.',
             '// The PC Options menu texts: key, then EN, FR, GE, IT, JP, SP, HU (nullptr: fall back to English).',
             'struct MenuText {',
             '    const char* key;',
             '    const char* text[7];',
             '};',
             'const MenuText kMenuTexts[] = {']
    for key in sorted(keys):
        cells = []
        for lang in LANGS:
            value = tables[lang].get(key)
            cells.append(c_string(value) if value else 'nullptr')
        lines.append('    {%s, {%s}},' % (c_string(key), ', '.join(cells)))
    lines += ['};', '']
    with open(OUT, 'wb') as f:
        f.write('\n'.join(lines).encode('ascii'))
    have = [l for l in LANGS if tables[l]]
    print('wrote %s: %d keys, languages %s' % (OUT, len(keys), ', '.join(have)))


if __name__ == '__main__':
    main()
