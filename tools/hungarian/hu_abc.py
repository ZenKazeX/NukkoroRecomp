def mirror(pix, w):
    return {(w - 1 - x, y): v for (x, y), v in pix.items()}

def make_alphabet(body):
    g = {}
    for c, (p, w) in body.g.items():
        if len(c) == 1 and (c.isalnum() or c in ".-'"):
            g[c] = (p, w)
    real = set(g)
    # capitals the pictures lack
    for c, w in (('A', 10), ('C', 10), ('E', 9), ('G', 10), ('J', 9), ('K', 10), ('O', 10), ('Q', 10), ('U', 10),
                 ('W', 14), ('X', 10), ('Y', 10), ('Z', 10)):
        if c not in g: g[c] = (t.raster(t.caps(c, w), w), w)
    if 'R' not in g:   # the P with a leg
        pp, pw = g['P']
        leg = t.raster([([(pw / 2.0 + 0.5, -9.0), (pw - 0.6, 1.0)], 0)], pw)
        r = dict(pp)
        for k, v in leg.items(): r[k] = max(r.get(k, 0), v)
        g['R'] = (r, pw)
    g['I'] = g['l']                                   # the face's I is the l's stem
    # lowercase the pictures lack
    for c in ('k', 'x'):
        if c not in g: g[c] = (t.raster(t.lower(c), 9), 9)
    if 'q' not in g: g['q'] = (mirror(g['p'][0], g['p'][1]), g['p'][1])
    if 'j' not in g:   # the i with a stem down to row 6 and a foot to the left (the glyph is 3 columns wider)
        i, iw = g['i']
        sh = 3
        j = {(x + sh, y): v for (x, y), v in i.items()}
        desc = t.raster([([(1.7 + sh, -12.0), (1.7 + sh, 6.0)], 0), ([(1.7 + sh, 5.0), (0.2, 5.0)], 0)], iw + sh)
        desc = t.raster([([(1.7 + sh, -11.5), (1.7 + sh, 5.5), (0.3 + sh - 1.5, 6.0), (0.4, 6.0)], 0.9)], iw + sh)
        for k, v in desc.items(): j[k] = max(j.get(k, 0), v)
        g['j'] = (j, iw + sh)
    real -= {'A', 'k'}      # drawn earlier for the Hz screen, not the game's
    return g, real

def acute(offsets=(0,)):
    pix = {}
    for x0 in offsets:
        for i in range(4):
            for dx in (0, 1):
                pix[(x0 + i + dx, -i)] = 255
    return pix

def dots(w):
    pix = {}
    for x0 in (w // 2 - 3, w // 2 + 1):
        for y in (0, -1, -2):
            pix[(x0, y)] = 255; pix[(x0 + 1, y)] = 255
    return pix

def accented(g, base, kind, capital):
    p, w = g[base]
    if kind == 'i-dotless':
        p = {k: v for k, v in p.items() if k[1] >= -12}
    top = min(y for _, y in p)
    gap = 2
    if kind == 'acute' or kind == 'i-dotless':
        m, mw = acute(), 5
    elif kind == 'double':
        m, mw = acute((0, 4)), 9
    else:
        m, mw = dots(w), w
    ox = (w - mw) // 2
    out = dict(p)
    for (x, y), v in m.items():
        out[(x + ox, y + top - gap)] = v
    return out, w

