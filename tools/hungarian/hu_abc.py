def render(files, out_png):
    body = b.build(files)[0]
    g, real = make_alphabet(body)
    caps = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
    low = "abcdefghijklmnopqrstuvwxyz"
    rows = [[(c, g[c], c in real) for c in caps], [(c, g[c], c in real) for c in low]]
    acc = []
    for ch, base, kind in (('Á', 'A', 'acute'), ('É', 'E', 'acute'), ('Í', 'I', 'acute'), ('Ó', 'O', 'acute'),
                           ('Ö', 'O', 'dots'), ('Ő', 'O', 'double'), ('Ú', 'U', 'acute'), ('Ü', 'U', 'dots'),
                           ('Ű', 'U', 'double')):
        acc.append((ch, accented(g, base, kind, True), False))
    acc2 = []
    for ch, base, kind in (('á', 'a', 'acute'), ('é', 'e', 'acute'), ('í', 'i', 'i-dotless'), ('ó', 'o', 'acute'),
                           ('ö', 'o', 'dots'), ('ő', 'o', 'double'), ('ú', 'u', 'acute'), ('ü', 'u', 'dots'),
                           ('ű', 'u', 'double')):
        acc2.append((ch, accented(g, base, kind, False), False))
    rows += [acc, acc2]
    S, pad = 4, 5
    line_h = 36
    W = max(sum(w + pad for _, (p, w), _r in r) for r in rows) * S + 8 * S
    H = (line_h * len(rows) + 4) * S
    img = [[(0, 0, 0)] * W for _ in range(H)]
    for ri, r in enumerate(rows):
        x = 4
        base_y = (ri * line_h + 27) * S
        for ch, (p, w), is_real in r:
            for (px, py), v in p.items():
                col = (v, v, v) if is_real else (v, int(v * 0.85), int(v * 0.55))   # generated letters tinted
                for dy in range(S):
                    for dx in range(S):
                        X = (x + px) * S + dx; Y = base_y + py * S + dy
                        if 0 <= X < W and 0 <= Y < H: img[Y][X] = col
            x += w + pad
    raw = b''.join(b'\0' + b''.join(bytes(c) for c in row) for row in img)
    def ch(tag, data):
        c = struct.pack('>I', len(data)) + tag + data
        return c + struct.pack('>I', zlib.crc32(tag + data) & 0xffffffff)
    open(out_png, 'wb').write(b'\x89PNG\r\n\x1a\n' + ch(b'IHDR', struct.pack('>IIBBBBB', W, H, 8, 2, 0, 0, 0)) +
                              ch(b'IDAT', zlib.compress(raw)) + ch(b'IEND', b''))
    print('real:', ''.join(sorted(c for c in real if c.isalpha())))

if __name__ == '__main__':
    render(sys.argv[1], sys.argv[2])
