"""The Hungarian alphabet in the Hz screen's thin squared face: the game's own letters where its pictures have them,
the rest generated by thin_face.py (monoline skeletons calibrated on the real glyphs), accents drawn as the face's own
strokes. Writes a specimen PNG.   python -I hu_abc.py <game files dir> <out.png>
"""
