"""Generates runtime/src/gekko/native_hungarian_draft.cpp: machine-drafted Hungarian for the messages the user's package
does not cover (shadow_hu_missing.txt). Inputs: missing.json (section, position, id, english) and the drafts out_*.json
(section, position, hungarian), one per shard. Every draft is checked: same message, characters the game font has,
segments (between the in-game line breaks) <= 42 characters. Run:
    python -I gen_hu_draft.py <tr dir: missing.json, out_*.json, allowed_chars.txt> <out.cpp>
"""
import glob, json, os, sys

def lit(s):
    out = []
    for b in s.encode('utf-8'):
        c = chr(b)
        if b < 0x20 or b >= 0x7F or c in ('"', chr(92), '?'):
            out.append(chr(92) + '%03o' % b)
        else:
            out.append(c)
    return '"' + ''.join(out) + '"'

def main(tr, dst):
    missing = json.load(open(os.path.join(tr, 'missing.json'), encoding='utf-8'))
    allowed = set(open(os.path.join(tr, 'allowed_chars.txt'), encoding='utf-8').read().strip()) | {' ', '♪'}
    drafts = {}
    for f in sorted(glob.glob(os.path.join(tr, 'out_*.json'))):
        for d in json.load(open(f, encoding='utf-8')):
            drafts[(d['section'], d['position'])] = d['hungarian']
    overrides = {}
    ov_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'draft_overrides.json')
    if os.path.exists(ov_path):
        for k, v in json.load(open(ov_path, encoding='utf-8')).items():
            if ':' in k and not k.startswith('_'):
                sec, pos = k.split(':')
                overrides[(sec, int(pos))] = v
    rows, bad = [], []
    for m in missing:
        key = (m['section'], m['position'])
        h = overrides.get(key, drafts.get(key))
        if h is None:
            bad.append((key, 'no draft')); continue
        if not h.strip() and m['english'].strip():
            bad.append((key, 'empty')); continue
        segs = h.split(' / ')
        if any(len(sg) > 42 for sg in segs):
            bad.append((key, 'long segment')); continue
        if any(c not in allowed for c in h.replace(' / ', ' ')):
            bad.append((key, 'glyph ' + ''.join(sorted({c for c in h if c not in allowed})))); continue
        rows.append((m['section'], m['position'], h.replace(' / ', '\n')))
    rows.sort(key=lambda r: (r[0], r[1]))
    out = ['// GENERATED by tools/hungarian/gen_hu_draft.py: machine-drafted Hungarian for messages the package lacks.',
           '#include "gekko/native_hungarian_text.h"', '', 'namespace gekko::hungarian {', '', 'const Row kDraftRows[] = {']
    for fam, idx, text in rows:
        out.append('    {%s, %d, %s},' % (lit(fam), idx, lit(text)))
    out += ['};', 'const std::size_t kDraftRowCount = sizeof(kDraftRows) / sizeof(kDraftRows[0]);', '',
            '}  // namespace gekko::hungarian', '']
    open(dst, 'w', newline='\n', encoding='ascii').write('\n'.join(out))
    print(len(rows), 'draft rows of', len(missing), '; rejected', len(bad))
    for k, why in bad[:40]: print('  ', k, why)

main(sys.argv[1], sys.argv[2])
