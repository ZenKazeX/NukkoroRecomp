def lit(s):
    out = []
    for b in s.encode('utf-8'):
        c = chr(b)
        if b < 0x20 or b >= 0x7F or c in ('"', chr(92), '?'):
            out.append(chr(92) + '%03o' % b)
        else:
            out.append(c)
    return '"' + ''.join(out) + '"'

def main(src, dst):
    rows = []
    for line in open(os.path.join(src, 'shadow_hu_patch.jsonl'), encoding='utf-8'):
        d = json.loads(line)
        if d['section'] == 'PC Options menu':
            continue
        rows.append((d['section'], d['position'], d['hungarian'].replace(' / ', '\n')))
    rows.sort(key=lambda r: (r[0], r[1]))
    opts = json.load(open(os.path.join(src, 'strings_hu.json'), encoding='utf-8'))
    out = ['// GENERATED by tools/hungarian/gen_hu_data.py from the user\'s Hungarian localization package. Do not edit.',
           '#include "gekko/native_hungarian_text.h"', '', 'namespace gekko::hungarian {', '',
           'const Row kRows[] = {']
    for fam, idx, text in rows:
        out.append('    {%s, %d, %s},' % (lit(fam), idx, lit(text)))
    out += ['};', 'const std::size_t kRowCount = sizeof(kRows) / sizeof(kRows[0]);', '',
            'const OptionString kOptionStrings[] = {']
    for k, v in sorted(opts.items()):
        out.append('    {%s, %s},' % (lit(k), lit(v.replace(' / ', '\n'))))
    out += ['};', 'const std::size_t kOptionStringCount = sizeof(kOptionStrings) / sizeof(kOptionStrings[0]);', '',
            'const SaveMessage kSaveMessages[] = {']
    for idx, text in sorted(PC_SAVE.items()):
        out.append('    {%d, %s},' % (idx, lit(text)))
    out += ['};', 'const std::size_t kSaveMessageCount = sizeof(kSaveMessages) / sizeof(kSaveMessages[0]);', '',
            '}  // namespace gekko::hungarian', '']
    open(dst, 'w', newline='\n', encoding='ascii').write('\n'.join(out))
    print(len(rows), 'rows,', len(opts), 'option strings')

main(sys.argv[1], sys.argv[2])
