"""Quantizes the Hungarian 50/60 Hz picture (render_palsel.ps1's raw RGB, 512 x 512) to the game's C8 + RGB565 texture
format and writes runtime/src/gekko/native_hungarian_palsel.cpp (palette + run-length pixels in the GameCube's 8 x 4
tile order). Run: python -I make_palsel.py <palsel_hu.raw> <out.cpp>
"""
import sys

W = H = 512

def rgb565(c):
    r, g, b = c
    return (r * 31 + 127) // 255 << 11 | (g * 63 + 127) // 255 << 5 | (b * 31 + 127) // 255

def from565(v):
    return (((v >> 11) & 31) * 255 // 31, ((v >> 5) & 63) * 255 // 63, (v & 31) * 255 // 31)

def median_cut(colors, n):
    # colors: {rgb565: count}
    boxes = [list(colors.items())]
    while len(boxes) < n:
        boxes.sort(key=lambda b: -len(b))
        box = boxes.pop(0)
        if len(box) < 2:
            boxes.append(box)
            break
        best = None
        for ch in range(3):
            vals = [from565(c)[ch] for c, _ in box]
            span = max(vals) - min(vals)
            if best is None or span > best[0]:
                best = (span, ch)
        ch = best[1]
        box.sort(key=lambda it: from565(it[0])[ch])
        half = sum(w for _, w in box) / 2.0
        acc = 0
        cut = 1
        for i, (_, w) in enumerate(box):
            acc += w
            if acc >= half:
                cut = max(1, min(len(box) - 1, i + 1))
                break
        boxes.append(box[:cut])
        boxes.append(box[cut:])
    pal = []
    for box in boxes:
        tw = sum(w for _, w in box)
        r = sum(from565(c)[0] * w for c, w in box) / tw
        g = sum(from565(c)[1] * w for c, w in box) / tw
        b = sum(from565(c)[2] * w for c, w in box) / tw
        pal.append(rgb565((int(r + .5), int(g + .5), int(b + .5))))
    return pal

def main(raw_path, out_path):
    raw = open(raw_path, 'rb').read()
    assert len(raw) == W * H * 3
    px = [rgb565((raw[i], raw[i + 1], raw[i + 2])) for i in range(0, len(raw), 3)]
    counts = {}
    for v in px:
        counts[v] = counts.get(v, 0) + 1
    # black is index 0 and stays exactly black
    pal = [0] if len(counts) <= 256 else None
    if len(counts) <= 256:
        pal = sorted(counts)
    else:
        pal = median_cut(counts, 256)
        if 0 not in pal:
            pal[-1] = 0
    pal = (pal + [0] * 256)[:256]
    cache = {}
    def index_of(v):
        if v not in cache:
            c = from565(v)
            cache[v] = min(range(256), key=lambda k: sum((a - b) ** 2 for a, b in zip(from565(pal[k]), c)))
        return cache[v]
    idx = [index_of(v) for v in px]
    tiled = bytearray()
    for ty in range(0, H, 4):
        for tx in range(0, W, 8):
            for y in range(4):
                for x in range(8):
                    tiled.append(idx[(ty + y) * W + tx + x])
    runs = []
    i = 0
    while i < len(tiled):
        j = i
        while j < len(tiled) and tiled[j] == tiled[i] and j - i < 255:
            j += 1
        runs += [j - i, tiled[i]]
        i = j
    out = ['// GENERATED by tools/hungarian/make_palsel.py (picture: tools/hungarian/render_palsel.ps1). Do not edit.',
           '#include "gekko/native_hungarian_text.h"', '', 'namespace gekko::hungarian {', '',
           'const unsigned short kPalSelPalette[256] = {']
    for k in range(0, 256, 16):
        out.append('    ' + ', '.join('0x%04X' % v for v in pal[k:k + 16]) + ',')
    out += ['};', 'const unsigned char kPalSelRuns[] = {']
    for k in range(0, len(runs), 24):
        out.append('    ' + ', '.join(str(v) for v in runs[k:k + 24]) + ',')
    out += ['};', 'const unsigned kPalSelRunBytes = %d;' % len(runs), '', '}  // namespace gekko::hungarian', '']
    open(out_path, 'w', newline='\n', encoding='ascii').write('\n'.join(out))
    print('colors', len(counts), 'runs', len(runs) // 2, 'bytes', len(runs))

main(sys.argv[1], sys.argv[2])
