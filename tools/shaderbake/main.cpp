// Build-time shader baker.
//
// Compiles the presenter's blit programs to DXBC and generates a C++
// translation unit embedding the bytecode (gekko::presentshaders,
// present_shader_cache.h), so no executable contains a shader compiler or
// performs shader compilation. A compile failure fails the build: there is
// deliberately no runtime fallback that could hide an incomplete bake.
//
// 2026-10-05: the second set, the legacy recovered-GX raster programs and
// their diagnostic experiments, was deleted with the legacy GX raster.
//
// Usage: shaderbake present <output.cpp>

#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <string>

#include <d3dcompiler.h>

#include "present_shader.h"

namespace {

struct BakeTarget {
    const char* entry;
    const char* target;
};

// Presentation blit, for the presenter's own device. DXBC is device-agnostic,
// so this one bake serves every presenter.
constexpr BakeTarget kPresentTargets[] = {
    {"VSPresentBlit", "vs_5_1"},
    {"PSPresentBlit", "ps_5_1"},
    {"PSPresentBlend", "ps_5_1"},
};

unsigned long long source_hash(const char* source, const char* entry, const char* target) {
    unsigned long long hash = 1469598103934665603ull;
    const auto mix = [&](const char* bytes, std::size_t count) {
        for (std::size_t index = 0; index < count; ++index) {
            hash ^= static_cast<unsigned char>(bytes[index]);
            hash *= 1099511628211ull;
        }
    };
    mix(source, std::strlen(source));
    if (entry != nullptr) mix(entry, std::strlen(entry));
    if (target != nullptr) mix(target, std::strlen(target));
    return hash;
}

}  // namespace

int main(int argc, char** argv) {
    if (argc != 3 || std::strcmp(argv[1], "present") != 0) {
        std::fprintf(stderr, "usage: shaderbake present <output.cpp>\n");
        return 1;
    }
    const char* const output_path = argv[2];

    std::string generated;
    generated +=
        "// Generated by tools/shaderbake - do not edit. Every shader program of\n"
        "// this set is compiled here, at build time; the executable contains no\n"
        "// shader compiler.\n";
    generated += "#include \"gekko/present_shader_cache.h\"\n\n";
    generated += "namespace gekko {\nnamespace presentshaders {\n\n";

    std::string table;
    table += "const EmbeddedShader kEmbeddedShaders[] = {\n";

    for (const BakeTarget& bake : kPresentTargets) {
        ID3DBlob* blob = nullptr;
        ID3DBlob* errors = nullptr;
        const UINT flags = D3DCOMPILE_ENABLE_STRICTNESS | D3DCOMPILE_IEEE_STRICTNESS |
                           D3DCOMPILE_OPTIMIZATION_LEVEL3 |
                           D3DCOMPILE_ENABLE_UNBOUNDED_DESCRIPTOR_TABLES;
        // The source name is the one every earlier bake used; it is kept so
        // the embedded bytecode stays byte-identical to theirs.
        const HRESULT status =
            D3DCompile(kGxPresentShader, std::strlen(kGxPresentShader),
                       "recovered_gx_native_raster.hlsl", nullptr, nullptr, bake.entry,
                       bake.target, flags, 0, &blob, &errors);
        if (FAILED(status) || blob == nullptr) {
            std::fprintf(stderr, "shaderbake: %s (%s) failed to compile (0x%08lX)\n",
                         bake.entry, bake.target, static_cast<unsigned long>(status));
            if (errors != nullptr) {
                std::fprintf(stderr, "%.*s\n", static_cast<int>(errors->GetBufferSize()),
                             static_cast<const char*>(errors->GetBufferPointer()));
                errors->Release();
            }
            if (blob != nullptr) blob->Release();
            return 1;
        }
        if (errors != nullptr) errors->Release();

        const unsigned char* bytes = static_cast<const unsigned char*>(blob->GetBufferPointer());
        const std::size_t size = blob->GetBufferSize();
        if (size < 4 || std::memcmp(bytes, "DXBC", 4) != 0) {
            std::fprintf(stderr, "shaderbake: %s produced invalid bytecode\n", bake.entry);
            blob->Release();
            return 1;
        }

        char line[128];
        std::snprintf(line, sizeof(line), "static const unsigned char kBlob_%s[] = {\n",
                      bake.entry);
        generated += line;
        for (std::size_t index = 0; index < size; ++index) {
            if ((index & 15u) == 0u) generated += "    ";
            std::snprintf(line, sizeof(line), "0x%02X,", bytes[index]);
            generated += line;
            if ((index & 15u) == 15u) generated += "\n";
        }
        if ((size & 15u) != 0u) generated += "\n";
        generated += "};\n\n";

        std::snprintf(line, sizeof(line), "    {\"%s\", \"%s\", kBlob_%s, sizeof(kBlob_%s)},\n",
                      bake.entry, bake.target, bake.entry, bake.entry);
        table += line;

        std::fprintf(stdout, "shaderbake: %s (%s) -> %zu bytes (source hash %016llx)\n",
                     bake.entry, bake.target, size,
                     source_hash(kGxPresentShader, bake.entry, bake.target));
        blob->Release();
    }

    table += "};\n";
    generated += table;

    char footer[256];
    std::snprintf(footer, sizeof(footer),
                  "const std::size_t kEmbeddedShaderCount = %zu;\n"
                  "const unsigned long long kShaderSourceHash = 0x%016llxull;\n\n"
                  "}  // namespace presentshaders\n}  // namespace gekko\n",
                  sizeof(kPresentTargets) / sizeof(kPresentTargets[0]),
                  source_hash(kGxPresentShader, nullptr, nullptr));
    generated += footer;

    std::FILE* out = std::fopen(output_path, "wb");
    if (out == nullptr) {
        std::fprintf(stderr, "shaderbake: cannot open %s\n", output_path);
        return 1;
    }
    const std::size_t written = std::fwrite(generated.data(), 1, generated.size(), out);
    std::fclose(out);
    if (written != generated.size()) {
        std::fprintf(stderr, "shaderbake: short write to %s\n", output_path);
        return 1;
    }
    return 0;
}
