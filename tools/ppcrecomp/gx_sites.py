"""GX write-gather pipe sites for the generator (ppcrecomp --gx-sites).

Every store of the main DOL to the write-gather pipe page (EA 0xCC008000) and
the family the generator lowers it to (docs/native-time-20261005/
GX_DATA_PLANE.md): dead transport emits nothing; the draw-sync token, draw-done,
copy-trigger, primitive-header and vertex sites become native calls. The
sites and families come from tools/gx_site_inventory.py (whole-image
constant propagation with the EABI call rule; its classifier tests are
tools/ppcrecomp/test_gx_sites.py):

  gx_sites.py --dol <main.dol> --functions <functions.csv> --jump-tables <jump-tables.txt> --out <file>
  gx_sites.py --dol <main.dol> --functions <functions.csv> --jump-tables <jump-tables.txt> --check <file>

--check fails (exit 1) unless the file is exactly what the inventory produces
from these inputs now (CTest native_gx_sites); --out refuses a list with an
`unknown` site.
"""
from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parents[1]
if str(TOOLS) not in sys.path:
    sys.path.insert(0, str(TOOLS))
from gx_site_inventory import report  # noqa: E402

HEADER = [
    "# GX write-gather pipe sites for ppcrecomp --gx-sites: site word family [note].",
    "# docs/native-time-20261005/GX_DATA_PLANE.md: every store of the main DOL to the pipe page (EA 0xCC008000)",
    "# and what the generator emits there - dead: nothing (an update form keeps its base update);",
    "# draw_sync_token / draw_sync_token_irq / draw_done / copy_trigger / primitive_opcode / primitive_count /",
    "# vertex: the native call of that family. Each site is pinned by its DOL instruction word.",
    "# Generated by tools/ppcrecomp/gx_sites.py from tools/gx_site_inventory.py.",
    "# Do not edit; regenerate (the native_gx_sites test refuses a stale file).",
]


def render(dol: Path, functions: Path, jump_tables: Path, workers: int) -> tuple[str, list]:
    data = report(dol, functions, jump_tables, workers=workers)
    lines = list(HEADER)
    unknown = []
    for site in data["sites"]:
        if site["family"] == "unknown":
            unknown.append(site)
        lines.append("0x%08X 0x%08X %s  fn 0x%08X %s: %s" % (
            int(site["site"], 16), int(site["word"], 16), site["family"], int(site["function"], 16),
            site["mnemonic"], site["reason"]))
    return "\n".join(lines) + "\n", unknown


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dol", type=Path, required=True)
    parser.add_argument("--functions", type=Path, required=True)
    parser.add_argument("--jump-tables", type=Path, required=True)
    parser.add_argument("--workers", type=int, default=min(16, os.cpu_count() or 1))
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--out", type=Path)
    group.add_argument("--check", type=Path)
    args = parser.parse_args(argv)
    text, unknown = render(args.dol, args.functions, args.jump_tables, args.workers)
    sites = text.count("\n") - len(HEADER)
    if args.out is not None:
        if unknown:
            print(f"{len(unknown)} sites are unknown (first {unknown[0]['site']}: {unknown[0]['reason']}); "
                  "nothing written")
            return 1
        with args.out.open("x", encoding="utf-8", newline="\n") as stream:
            stream.write(text)
        print(f"{sites} GX pipe sites written to {args.out}")
        return 0
    listed = args.check.read_text(encoding="utf-8")
    if listed != text:
        print("GX pipe site file is stale; regenerate it with --out")
        return 1
    if unknown:
        print(f"{len(unknown)} sites are unknown")
        return 1
    print(f"GX pipe sites current: {sites} sites")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
