"""Recognized jump tables for the generator's liveness pass (ppcrecomp --jump-tables).

A compiler switch table is a run of code addresses in .data that only its own
`lwzx; mtctr; bctr` dispatch reads (tables addressed off r2/r13 are not listed:
a small-data offset reaches them without a hi/lo pair). Seeding every one of its words as a
liveness root (the generator's default for data words) keeps the case arms of a
dead switch alive. With this file the generator treats the words of each listed
table as edges from the row holding its dispatch site - and still verifies, per
table, that every word is a code address, that no other row forms an address
inside the table and that no data word points into it; a table that fails
stays rooted.

The tables come from tools/platform_jump_table_dispatch.py (data-flow
recognizer, STRUCTURAL MATCH, 195 of 206 `bctr` sites on this DOL):

  jump_tables.py --dol <main.dol> --functions <functions.csv> --out <file>
  jump_tables.py --dol <main.dol> --functions <functions.csv> --check <file>

--check fails (exit 1) unless the file is exactly what the recognizer produces
from these inputs now (CTest native_jump_tables).
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parents[1]
if str(TOOLS) not in sys.path:
    sys.path.insert(0, str(TOOLS))
from platform_jump_table_dispatch import scan_dispatches  # noqa: E402


def render(dol: Path, functions: Path) -> str:
    report = scan_dispatches(dol.read_bytes(), functions.read_bytes())
    lines = ["# Recognized jump tables for ppcrecomp --jump-tables: dispatch_site table entries.",
             "# Generated by tools/ppcrecomp/jump_tables.py from tools/platform_jump_table_dispatch.py.",
             "# Do not edit; regenerate (the native_jump_tables test refuses a stale file)."]
    for dispatch in sorted(report["dispatches"], key=lambda d: int(d["dispatch_site"], 16)):
        # A table addressed off r2/r13 can be read through a small-data offset
        # with no hi/lo pair the generator could see: it stays rooted.
        if dispatch["base_gpr"] in (2, 13):
            continue
        lines.append("0x%08X 0x%08X %d" % (int(dispatch["dispatch_site"], 16),
                                          int(dispatch["original_table_address"], 16),
                                          dispatch["admitted_unsigned_maximum"] + 1))
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dol", type=Path, required=True)
    parser.add_argument("--functions", type=Path, required=True)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--out", type=Path)
    group.add_argument("--check", type=Path)
    args = parser.parse_args(argv)
    text = render(args.dol, args.functions)
    if args.out is not None:
        with args.out.open("x", encoding="utf-8", newline="\n") as stream:
            stream.write(text)
        print(f"{text.count(chr(10)) - 3} jump tables written to {args.out}")
        return 0
    listed = args.check.read_text(encoding="utf-8")
    if listed != text:
        print("jump tables file is stale; regenerate it with --out")
        return 1
    print(f"jump tables current: {text.count(chr(10)) - 3} tables")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
